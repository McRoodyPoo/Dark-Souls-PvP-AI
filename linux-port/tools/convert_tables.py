"""Mechanically convert metal-crow's switch-statement lookup tables into Python dicts.

  python tools/convert_tables.py      # writes ptde_ai/tables.py

Hand-copying ~4,000 case lines invites typos, so this parses the C directly.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# metal-crow's original repo: vendored here, or (in the GitHub fork) the folder above this one
UPSTREAM = next((d for d in (ROOT / "vendor" / "Dark-Souls-PvP-AI", ROOT.parent)
                 if (d / "Dark Souls AI C").exists()), ROOT / "vendor" / "Dark-Souls-PvP-AI")
SRC = UPSTREAM / "Dark Souls AI C"
OUT = ROOT / "ptde_ai" / "tables.py"


def read(name: str) -> str:
    text = (SRC / name).read_text(encoding="latin-1").replace("\r", "")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def enum_values(header: str, enum_name: str) -> dict[str, int]:
    body = re.search(r"enum\s+%s\s*\{(.*?)\}" % enum_name, header, re.S).group(1)
    out = {}
    for name, val in re.findall(r"(\w+)\s*=\s*(\d+)", body):
        out[name] = int(val)
    return out


def function_body(src: str, name: str) -> str:
    m = re.search(r"\b%s\s*\([^)]*\)\s*\{" % re.escape(name), src)
    if not m:
        raise SystemExit(f"function {name} not found")
    depth, i = 1, m.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        i += 1
    return src[m.end():i - 1]


def switch_table(body: str, names: dict[str, int]) -> tuple[dict, object]:
    """case A: case B: return X;  ->  {A: X, B: X}; also returns the default value."""
    table, pending, default = {}, [], None
    tokens = re.findall(r"case\s+([\w.]+)\s*:|default\s*:|return\s+([^;]+);", body)
    in_default = False
    for case, ret in tokens:
        if case:
            pending.append(names.get(case, None) if not case.lstrip("-").isdigit() else int(case))
            if pending[-1] is None:
                raise SystemExit(f"unknown case label {case}")
        elif ret == "" and not case:      # 'default:' token
            in_default = True
        if ret:
            val = ret.strip()
            if val in names:
                val = names[val]
            elif re.fullmatch(r"-?\d+(\.\d+)?", val):
                val = float(val) if "." in val else int(val)
            else:  # e.g. `default: return animationType_id;` (identity), not a table entry
                pending, in_default = [], False
                continue
            if in_default and not pending:
                default = val
            for key in pending:
                table[key] = val
            pending, in_default = [], False
    return table, default


def main():
    anim_h = read("AnimationMappings.h")
    anim_c = read("AnimationMappings.c")
    weap_c = read("WeaponData.c")
    names = enum_values(anim_h, "AnimationTypesE")

    attack, _ = switch_table(function_body(anim_c, "isAttackAnimation"), names)
    dodge, _ = switch_table(function_body(anim_c, "isDodgeAnimation"), names)
    vuln, _ = switch_table(function_body(anim_c, "isVulnerableAnimation"), names)
    timings, timing_default = switch_table(function_body(anim_c, "dodgeTimings"), names)
    behavior, _ = switch_table(function_body(weap_c, "WeaponTypeToBehaviorVariation"), {})
    stamina, _ = switch_table(function_body(weap_c, "BehaviorAndAttackTypeToStaminaDrain"), {})
    compress, _ = switch_table(function_body(weap_c, "CompressAnimationTypes"), {})
    poise, _ = switch_table(function_body(weap_c, "WeaponAndAttackTypeToPoiseDamage"), {})

    def dump(name, d, comment):
        items = ", ".join(f"{k}: {v!r}" for k, v in sorted(d.items()))
        return f"# {comment}\n{name} = {{{items}}}\n"

    parts = [
        '"""GENERATED by tools/convert_tables.py from metal-crow/Dark-Souls-PvP-AI. Do not edit."""\n',
        "from enum import IntEnum\n\n",
        "class Anim(IntEnum):\n" + "".join(f"    {k} = {v}\n" for k, v in names.items()) + "\n",
        dump("ATTACK_ANIM", attack,
             "animation type -> 1 windup, 2 check subanimation, 3 hurtbox out, 4 like 2, 5 combined (0 = not an attack)"),
        dump("DODGE_ANIM", {k: v for k, v in dodge.items() if v}, "animation types that are rolls/backsteps"),
        dump("VULNERABLE_ANIM_ID", {k: v for k, v in vuln.items() if v}, "animation ids that lock the character in place"),
        dump("DODGE_TIMINGS", timings, "animation id -> seconds from animation start until the hurtbox appears"),
        f"DODGE_TIMING_DEFAULT = {timing_default!r}  # used for any attack id not in the table\n\n",
        dump("WEAPON_TYPE_TO_BEHAVIOR", behavior, "weapon_id // 1000 -> behavior variation id"),
        dump("STAMINA_DRAIN", stamina, "behavior * 1000 + animation type -> stamina cost"),
        dump("COMPRESS_ANIM", compress, "animation types that share poise damage with another"),
        dump("POISE_DAMAGE", poise, "weapon_id // 1000 * 1000 + compressed animation type -> poise damage"),
    ]
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(attack)} attack types, {len(timings)} timings, "
          f"{len(stamina)} stamina entries, {len(poise)} poise entries, default timing {timing_default}")


if __name__ == "__main__":
    main()
